        <article class="about-panel">
            <p class="eyebrow">History</p>
            <h2>How Krishi Vigyan Kendras became a national extension model</h2>
            <p>The Education Commission of 1964-66 recommended specialized institutions for vocational education in agriculture and related fields. These recommendations were discussed by the Ministry of Education, Ministry of Agriculture, Planning Commission, ICAR, and allied institutions between 1966 and 1972.</p>
            <p>ICAR proposed Krishi Vigyan Kendras as innovative institutions to provide vocational training to practicing farmers, school dropouts, and field-level extension functionaries. In August 1973, the ICAR Standing Committee on Agricultural Education recognized KVKs as nationally important for improving agricultural production and farming livelihoods.</p>
        </article>
        <article class="about-panel about-panel--dark" id="overview">
            <p class="eyebrow">KVK overview</p>
            <ul class="about-feature-list">
